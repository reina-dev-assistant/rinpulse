#!/usr/bin/env bun
// Regenerates the roadmap section of README.md from docs/roadmap.json (the one data file; the landing page in site/
// imports the same file). Run `bun scripts/roadmap-sync.ts` after editing the JSON, or with --check in CI to fail when
// the README is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Group = { id: 'doing' | 'next' | 'later'; title: string; items: string[] };
type Roadmap = { product: string; updated: string; groups: Group[] };

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const README = join(ROOT, 'README.md');
const START = '<!-- roadmap:start -->';
const END = '<!-- roadmap:end -->';

function render(data: Roadmap): string {
  const lines = [
    START,
    '<!-- Generated by scripts/roadmap-sync.ts from docs/roadmap.json. Edit the JSON, not this block. -->',
    '',
  ];
  for (const group of data.groups) {
    lines.push(`**${group.title}**`, '');
    for (const item of group.items) lines.push(`- ${item}`);
    lines.push('');
  }
  lines.push(`Diperbarui ${data.updated}. Tanpa tanggal: urutannya bisa berubah.`, END);
  return lines.join('\n');
}

const data = JSON.parse(readFileSync(join(ROOT, 'docs', 'roadmap.json'), 'utf8')) as Roadmap;
for (const g of data.groups) {
  if (!['doing', 'next', 'later'].includes(g.id)) throw new Error(`unknown group id: ${g.id}`);
  if (g.items.some((i) => typeof i !== 'string' || !i.trim())) throw new Error(`empty item in ${g.id}`);
}

const readme = readFileSync(README, 'utf8');
const a = readme.indexOf(START);
const b = readme.indexOf(END);
if (a < 0 || b < a) throw new Error(`README.md needs ${START} and ${END}`);
const next = readme.slice(0, a) + render(data) + readme.slice(b + END.length);

if (process.argv.includes('--check')) {
  if (next !== readme) {
    console.error('README.md roadmap is stale: run `bun scripts/roadmap-sync.ts`');
    process.exit(1);
  }
} else if (next !== readme) {
  writeFileSync(README, next);
  console.log('README.md roadmap updated');
} else {
  console.log('README.md roadmap already current');
}
