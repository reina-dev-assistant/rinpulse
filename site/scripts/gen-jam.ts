// Writes src/jam.ts from the watch catalog in WatchModels.kt, so the site, the app and the README
// agree on one list. Run `bun run jam` after changing the catalog.
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "../../modules/huawei-wear/android/src/main/java/com/joyodigitama/huaweiwear/WatchModels.kt";
const kt = readFileSync(new URL(SOURCE, import.meta.url), "utf8");

const tested: string[] = [];
const classic: string[] = [];
const le: string[] = [];
const pake: string[] = [];
const seen = new Set<string>();

for (const line of kt.split("\n")) {
  const m = line.match(/^\s*(br|le)\("([^"]+)"(.*)\),\s*$/);
  if (!m) continue;
  const [, kind, name, rest] = m;
  if (seen.has(name) && !rest.includes("tested = true")) continue;
  seen.add(name);
  if (rest.includes("tested = true")) tested.push(name);
  else if (rest.includes("pake = true")) pake.push(name);
  else (kind === "br" ? classic : le).push(name);
}

if (tested.length === 0 || classic.length === 0 || le.length === 0) {
  throw new Error("WatchModels.kt: catalog format changed, update scripts/gen-jam.ts");
}

const list = (name: string, items: string[]) =>
  `export const ${name} = ${JSON.stringify(items, null, 2)} as const;\n`;

writeFileSync(
  new URL("../src/jam.ts", import.meta.url),
  [
    "// Generated by scripts/gen-jam.ts from WatchModels.kt. Do not edit; run `bun run jam`.",
    "",
    list("JAM_SUDAH_DIUJI", tested),
    list("JAM_EKSPERIMEN_CLASSIC", classic),
    list("JAM_EKSPERIMEN_LE", le),
    list("JAM_BELUM_PAKE", pake),
    "export const JAM_TOTAL =",
    "  JAM_SUDAH_DIUJI.length + JAM_EKSPERIMEN_CLASSIC.length + JAM_EKSPERIMEN_LE.length + JAM_BELUM_PAKE.length;",
    "",
    "/** Models JoyoFit connects to: everything except the Honor pairing it cannot do yet. */",
    "export const JAM_BISA_DICOBA =",
    "  JAM_SUDAH_DIUJI.length + JAM_EKSPERIMEN_CLASSIC.length + JAM_EKSPERIMEN_LE.length;",
    "",
  ].join("\n"),
);
