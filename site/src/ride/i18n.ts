const dictionaries: Record<Lang, Record<TKey, string>> = { id, en };

function detectLang(): Lang {
  if (typeof window === "undefined") return "id";
  const q = new URLSearchParams(window.location.search).get("lang");
  if (q === "id" || q === "en") return q;
  const stored = loadSettings().lang;
  if (stored) return stored;
  return navigator.language.toLowerCase().startsWith("id") ? "id" : "en";
}

let current: Lang = detectLang();
const listeners = new Set<() => void>();

export function setLang(lang: Lang): void {
  current = lang;
  saveSettings({ lang });
  document.documentElement.lang = lang;
  for (const fn of listeners) fn();
}

export function getLang(): Lang {
  return current;
}

export type TFn = (key: TKey, vars?: Record<string, string | number>) => string;

export const translate: TFn = (key, vars) => {
  let text: string = dictionaries[current][key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
};

/** Re-renders the caller when the language changes; the returned `t` is stable per language. */
export function useT(): { t: TFn; lang: Lang } {
  const lang = useSyncExternalStore(
    (fn) => {
      listeners.add(fn);
      return () => listeners.delete(fn);
    },
    () => current,
    () => "id" as Lang,
  );
  return { t: translate, lang };
}
